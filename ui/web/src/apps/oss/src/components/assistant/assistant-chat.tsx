import {
  Button,
  EmptyList,
  TextArea,
  Typography,
} from "@plakar-ui/ui/components";
import { KeyboardEvent, useEffect, useRef, useState } from "react";

import { AssistantMessage } from "./assistant-message";
import { suggestionsFor } from "./assistant.constants";

import { AssistantPage, AssistantStatus } from "~/api/assistant/schema";
import { AssistantChat as AssistantChatState } from "~/hooks/use-assistant-chat";

type AssistantChatProps = {
  chat: AssistantChatState;
  status?: AssistantStatus;
  // What the UI shows behind the drawer; each message tells the model.
  page: AssistantPage;
};

// Where the answers come from, and so where what the tools read goes.
function describeProvider(status?: AssistantStatus) {
  if (!status?.model || !status.provider) {
    return "Answers are generated by a language model from what the tools read in this repository. Check them before acting on them.";
  }
  if (status.local) {
    return `Answers are generated by ${status.model} running on this machine through ${status.provider}; nothing is sent elsewhere. Check them before acting on them.`;
  }
  return `Answers are generated by ${status.model}. What the tools read in this repository is sent to ${status.provider} to do so. Check them before acting on them.`;
}

export function AssistantChat({ chat, status, page }: AssistantChatProps) {
  const { messages, isStreaming, send, stop, reset } = chat;
  const [draft, setDraft] = useState("");

  // Follow the answer as it grows, unless the reader scrolled up to read
  // something earlier: then the end marker leaves the view and the page
  // stays put until they come back to it.
  const endRef = useRef<HTMLDivElement>(null);
  const [follow, setFollow] = useState(true);
  useEffect(() => {
    const end = endRef.current;
    if (!end) {
      return;
    }
    const observer = new IntersectionObserver((entries) =>
      setFollow(entries.some((entry) => entry.isIntersecting))
    );
    observer.observe(end);
    return () => observer.disconnect();
  }, []);
  useEffect(() => {
    if (follow) {
      endRef.current?.scrollIntoView({ block: "end" });
    }
  }, [messages, follow]);

  const submit = (text: string) => {
    if (isStreaming || text.trim() === "") {
      return;
    }
    setDraft("");
    setFollow(true);
    void send(text, page);
  };

  const handleKeyDown = (event: KeyboardEvent) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      submit(draft);
    }
  };

  return (
    <div className="flex min-h-full flex-col gap-4">
      <div className="flex flex-1 flex-col gap-4">
        {messages.length === 0 ? (
          <EmptyList
            illustrationType="waving"
            title="Ask about this repository"
            description="The assistant reads the snapshots to answer. It cannot change them."
            actions={suggestionsFor(page).map((suggestion) => ({
              children: suggestion,
              variant: "secondary",
              size: "sm",
              onPress: () => submit(suggestion),
            }))}
          />
        ) : (
          messages.map((message) => (
            <AssistantMessage key={message.id} message={message} />
          ))
        )}
        <div ref={endRef} aria-hidden className="h-px shrink-0 scroll-mb-44" />
      </div>

      <form
        className="bg-primary sticky bottom-0 -mb-4 flex flex-col gap-2 pb-4"
        onSubmit={(event) => {
          event.preventDefault();
          submit(draft);
        }}
      >
        <TextArea
          aria-label="Message to the assistant"
          placeholder="Ask about snapshots, files, sizes…"
          rows={2}
          value={draft}
          onChange={setDraft}
          onKeyDown={handleKeyDown}
        />
        <div className="flex items-center justify-between gap-2">
          <Button
            variant="tertiary"
            size="sm"
            leftIcon="plus"
            onPress={reset}
            isDisabled={messages.length === 0}
          >
            New conversation
          </Button>
          {isStreaming ? (
            <Button
              variant="secondary"
              size="sm"
              leftIcon="stop"
              onPress={stop}
            >
              Stop
            </Button>
          ) : (
            <Button
              type="submit"
              size="sm"
              leftIcon="paper-plane"
              isDisabled={draft.trim() === ""}
            >
              Send
            </Button>
          )}
        </div>
        <Typography size="xs" className="text-tertiary">
          {describeProvider(status)}
        </Typography>
      </form>
    </div>
  );
}
