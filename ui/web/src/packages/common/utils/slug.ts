function randomItem<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

type displaySlugParams = {
  prefix?: string;
  separator?: string;
  capitalize?: boolean;
};

export function Slug() {
  const adj = randomItem(adjectives);
  const noun = randomItem(nouns);

  return {
    toString: (
      {
        prefix = "",
        separator = "-",
        capitalize = false,
      }: displaySlugParams = {
        prefix: "",
        separator: "-",
        capitalize: false,
      }
    ) => {
      const dadj = capitalize
        ? adj.charAt(0).toUpperCase() + adj.slice(1)
        : adj;
      const dnoun = capitalize
        ? noun.charAt(0).toUpperCase() + noun.slice(1)
        : noun;

      return `${prefix}${dadj}${separator}${dnoun}`;
    },
  };
}
